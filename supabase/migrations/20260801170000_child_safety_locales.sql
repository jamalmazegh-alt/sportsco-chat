## 3. Inhalte oder Verhalten melden

- **In der App**: Jeder Beitrag, Kommentar und jede Chat-Nachricht verfügt über eine Melden-Schaltfläche, und jedes Mitglied kann über sein Profil oder das Meldeformular gemeldet werden. Meldungen erreichen die Vereinsverantwortlichen sofort (App, Push-Benachrichtigung und E-Mail); diese können Inhalte ausblenden oder löschen oder ein Mitglied ausschließen.
