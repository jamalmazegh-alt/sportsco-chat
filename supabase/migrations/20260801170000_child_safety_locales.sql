2. Wanneer inhoud CSAM vormt of wijst op een kind in gevaar, bewaren wij het bewijsmateriaal en melden wij dit aan de bevoegde autoriteiten van het land van het lid. Wij verlenen volledige medewerking aan rechtmatige verzoeken van autoriteiten.
3. De verantwoordelijken van de betrokken club worden geïnformeerd voor zover dat nodig is om de kinderen van hun club te beschermen.

## 5. Naleving van de wet

Clubero leeft de toepasselijke wetgeving inzake kinderbescherming en gegevensbescherming na, waaronder de AVG (ouderlijke toestemming voor gegevens van minderjarigen) en de nationale kinderbeschermingsregels van de landen waar de Dienst wordt gebruikt.

