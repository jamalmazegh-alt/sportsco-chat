- **Elterliche Einwilligung und Kontrolle.** Ein Minderjähriger wird von seinem Verein angemeldet und einem Elternteil oder Erziehungsberechtigten zugeordnet. Ein eigener Zugang wird nur freigeschaltet, wenn ein Elternteil dies ausdrücklich aktiviert. Fotos von Minderjährigen erfordern eine dokumentierte elterliche Einwilligung, und das öffentliche Profil eines Minderjährigen setzt eine ausdrückliche elterliche Genehmigung voraus.
