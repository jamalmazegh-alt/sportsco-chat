_Última actualización: 1 de agosto de 2026_

Clubero es una plataforma de gestión de clubes deportivos cuyos miembros incluyen menores. La protección de la infancia es un requisito de diseño del Servicio, no una opción. Esta página describe nuestras normas contra la explotación y el abuso sexual infantil (CSAE) y cómo las aplicamos.

## 1. Tolerancia cero con la CSAE

Prohibimos cualquier contenido o comportamiento que sexualice, abuse, explote o ponga en peligro a menores, incluidos, entre otros: material de abuso sexual infantil (CSAM), grooming o captación de menores, sextorsión, trata, y la difusión de datos personales de un menor con intención de causar daño. Todo contenido o comportamiento de este tipo conlleva la retirada inmediata, la cancelación de la cuenta y su denuncia a las autoridades competentes.

## 2. Cómo Clubero protege a los menores desde el diseño

- **Comunidades cerradas, solo por invitación.** Todas las interacciones ocurren dentro de un club. Solo se accede mediante una invitación emitida por sus responsables; no existe descubrimiento público de miembros ni mensajería privada entre usuarios cualesquiera.
- **Consentimiento y control parental.** Un menor es inscrito por su club y vinculado a un padre, madre o tutor legal. Solo obtiene su propio acceso si un progenitor lo activa expresamente. Las fotos de menores exigen un consentimiento parental registrado, y el perfil público de un menor requiere una autorización parental explícita.
- **Canales de comunicación limitados.** Los miembros se comunican a través del muro del club y de los chats de evento — espacios visibles para el grupo correspondiente, nunca canales privados individuales con desconocidos.

## 3. Denunciar un contenido o un comportamiento

- **En la aplicación**: cada publicación, comentario y mensaje de chat dispone de un botón de denuncia, y cualquier miembro puede ser denunciado desde su ficha o desde el formulario de denuncia. Las denuncias llegan de inmediato a los responsables del club (aplicación, notificación push y correo electrónico), que pueden ocultar o eliminar el contenido, o expulsar a un miembro.
- **Bloqueo**: cualquier miembro puede ocultar a otro miembro — su contenido y sus notificaciones desaparecen para quien lo bloquea.
- **Contacto directo**: cualquier persona (incluso sin cuenta) puede comunicar una preocupación a **safety@clubero.app**. Las denuncias se registran y el equipo de Clubero las examina con rapidez.

## 4. Tratamiento de las denuncias CSAE

1. Los contenidos denunciados se examinan con prioridad; todo contenido constitutivo de CSAE se retira de inmediato y la cuenta implicada se suspende.
2. Cuando un contenido constituye CSAM o revela a un menor en peligro, preservamos las pruebas y lo denunciamos a las autoridades competentes del país del miembro, y cooperamos plenamente con los requerimientos legales de las autoridades.
3. Los responsables del club afectado son informados en la medida necesaria para proteger a los menores de su club.

## 5. Cumplimiento legal

Clubero cumple la legislación aplicable en materia de protección de la infancia y de protección de datos, incluido el RGPD (consentimiento parental para los datos de menores) y las normativas nacionales de protección infantil de los países donde se usa el Servicio.

## 6. Punto de contacto designado

Preguntas o notificaciones relativas a la seguridad infantil, incluidas las de autoridades y reguladores: **safety@clubero.app**.
