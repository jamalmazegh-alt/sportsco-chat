## 4. Umgang mit CSAE-Meldungen

1. Gemeldete Inhalte werden vorrangig geprüft; als CSAE eingestufte Inhalte werden sofort entfernt und das betroffene Konto wird gesperrt.
2. Stellt ein Inhalt CSAM dar oder deutet auf ein gefährdetes Kind hin, sichern wir die Beweise und melden den Fall den zuständigen Behörden des Landes des Mitglieds. Wir kooperieren umfassend mit rechtmäßigen Anfragen der Behörden.
3. Die Verantwortlichen des betroffenen Vereins werden informiert, soweit dies zum Schutz der Kinder ihres Vereins erforderlich ist.

## 5. Rechtskonformität

Clubero hält die geltenden Gesetze zum Kinderschutz und zum Datenschutz ein, einschließlich der DSGVO (elterliche Einwilligung für Daten Minderjähriger) und der nationalen Kinderschutzvorschriften der Länder, in denen der Dienst genutzt wird.

## 6. Benannte Kontaktstelle

Fragen oder Hinweise zum Kinderschutz, auch von Behörden und Aufsichtsstellen: **safety@clubero.app**.
